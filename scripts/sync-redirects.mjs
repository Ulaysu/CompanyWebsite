// Writes vercel.json and public/_redirects from src/redirects.json.
// Usage: node scripts/sync-redirects.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const redirects = JSON.parse(readFileSync(new URL('src/redirects.json', root), 'utf8'))
const entries = Object.entries(redirects)

const vercel = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  cleanUrls: true,
  trailingSlash: false,
  redirects: entries.map(([source, destination]) => ({ source, destination, permanent: true })),
}
writeFileSync(new URL('vercel.json', root), JSON.stringify(vercel, null, 2) + '\n')

const width = Math.max(...entries.map(([from]) => from.length)) + 2
const netlify =
  '# Generated by scripts/sync-redirects.mjs from src/redirects.json. Do not edit by hand.\n' +
  entries.map(([from, to]) => `${from.padEnd(width)}${to.padEnd(width)}301`).join('\n') +
  '\n'
writeFileSync(new URL('public/_redirects', root), netlify)
console.log(`Wrote ${entries.length} redirects to vercel.json and public/_redirects`)
